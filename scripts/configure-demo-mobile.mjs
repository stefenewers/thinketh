#!/usr/bin/env node
// Make Expo's effective .env.local explicit before a phone demo. Never print the app key.
import { copyFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "apps/mobile/.env.local");
const raw = process.argv[2];
const fallback = process.argv.includes("--fallback");
if (!raw || raw.startsWith("--")) {
  console.error("Usage: node scripts/configure-demo-mobile.mjs <API_URL> [--fallback]");
  process.exit(2);
}
let url;
try {
  url = new URL(raw);
  if (!(["https:", "http:"].includes(url.protocol)) || url.username || url.password || url.search || url.hash) throw new Error("invalid URL");
} catch {
  console.error("Provide a plain http(s) API origin, without credentials or query parameters.");
  process.exit(2);
}
const apiUrl = url.href.replace(/\/$/, "");
let key = process.env.THINKETH_APP_KEY;
if (!key && existsSync(join(root, ".env"))) {
  const line = readFileSync(join(root, ".env"), "utf8").split(/\r?\n/).find((v) => /^THINKETH_APP_KEY=/.test(v));
  key = line?.slice("THINKETH_APP_KEY=".length).trim().replace(/^(['"])(.*)\1$/, "$2");
}
if (!key || /[\r\n]/.test(key)) {
  console.error("THINKETH_APP_KEY is missing. Set it in the shell or repo-root .env.");
  process.exit(2);
}
try {
  const res = await fetch(`${apiUrl}/health`, { signal: AbortSignal.timeout(10000) });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
} catch (err) {
  console.error(`API health check failed at ${apiUrl}/health: ${err instanceof Error ? err.message : String(err)}`);
  process.exit(1);
}
const content = `# Generated by scripts/configure-demo-mobile.mjs. Do not commit.\nEXPO_PUBLIC_API_URL=${apiUrl}\nEXPO_PUBLIC_THINKETH_APP_KEY=${key}\nEXPO_PUBLIC_USE_MOCK_API=false\nEXPO_PUBLIC_API_FALLBACK_TO_MOCK=${fallback}\n`;
if (existsSync(target) && readFileSync(target, "utf8") !== content) {
  const backup = `${target}.backup-${new Date().toISOString().replace(/[:.]/g, "-")}`;
  copyFileSync(target, backup);
  console.log("Previous .env.local saved as an ignored, timestamped backup.");
}
writeFileSync(target, content, { mode: 0o600 });
console.log(`Mobile demo configured for ${apiUrl}; mock fallback ${fallback ? "ON" : "OFF"}.`);
console.log("Restart Metro: cd apps/mobile && npx expo start --clear");
console.log("On the phone, long-press the Thinketh mark > Demo controls to verify this URL and reset the persona.");
